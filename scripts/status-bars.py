"""Regenerates src/statusBars.ts from public/assets/*.jpg.

Each phone's status bar uses a horizontal gradient sampled from the top row of
its screenshot, so the bar blends into the app. Run after adding screenshots.
"""
import glob
import json
import os

from PIL import Image

bars = {}
for path in sorted(glob.glob("public/assets/*.jpg")):
    image = Image.open(path).convert("RGB")
    stops = []
    for i in range(7):
        x = min(image.width - 1, round(i * (image.width - 1) / 6))
        r, g, b = image.getpixel((x, 2))
        stops.append(f"#{r:02x}{g:02x}{b:02x} {round(i * 100 / 6)}%")
    bars[os.path.basename(path)] = f"linear-gradient(90deg, {', '.join(stops)})"

with open("src/statusBars.ts", "w") as out:
    out.write("// Generated by scripts/status-bars.py from the top row of each screenshot.\n")
    out.write("export const STATUS_BARS: Record<string, string> = " + json.dumps(bars, indent=2) + ";\n")
print(len(bars), "screens")
